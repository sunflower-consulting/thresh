"""Many runs, one appendix.

An engagement accumulates runs: the first sweep, the five times a case was run
while its control arm was being argued about, the retest four weeks later. A
document reads ONE file. Choosing which run each case is quoted from is this
module's whole job, and it is a choice that must not be made by hand.

THE RULE, AND WHY IT IS NOT "THE LATEST RUN".

Per case, the newest VALIDATED QUOTABLE run. Three qualifiers, each load-bearing:

`quotable` keeps tuning runs out. They stay on disk, stay diffable, and never
reach a client. That is what makes testing the same thing five times safe.

`validated` per case rather than per run, because one run can validate one case
and reject another, and the case the run rejected should be quoted from the run
that rejected it, not omitted.

Newest rather than best. Quoting the run with the highest rate would be selecting
the result, which is the thing this entire tool exists to stop other tools doing.

IDEMPOTENT, AND TESTED AS SUCH. Delete the output, run it again, get the same
bytes. A consolidated file that drifts between runs is one nobody can review by
diffing, and reviewing by diffing is the only way anybody notices a change.

`leads/` IS EXCLUDED IN CODE. A garak or promptfoo hit is a place to look, not a
finding: there is no control arm behind it, nothing was proved out of band, and
its regex matched text the target authored. It reaches the report as a coverage
count in the not-tested section and nowhere else. Excluded here rather than by
convention, because a convention is what fails the week somebody is in a hurry.
"""
from __future__ import annotations

from pathlib import Path

from sunflower_stem.export import (
    CONTROL_MAPPING,
    MEASUREMENTS,
    exported_runs,
    load_exported_run,
)

#: Directories under an engagement that consolidation must never read. `leads/`
#: holds raw scanner output; `evidence/` is content-addressed blobs a human cites
#: by hash. Neither is a measurement.
NEVER_READ = frozenset({"leads", "evidence", "pdf", "build"})

#: Case states that may be quoted as a measured result. A case that was never
#: probed has no row to quote and is reported by the not-tested section instead.
QUOTABLE_STATES = frozenset({"validated", "reproduced", "rejected", "confirmed"})

#: The seam problem this file cannot solve on its own, written where whoever hits
#: it will be looking.
#:
#: The consuming schema types `run_id` as one string and its renderer prints it as
#: a single "Run" line, because it was designed when one run produced one file.
#: Consolidation spans runs by design, so `run_id` below is the NEWEST run quoted
#: and is not the whole provenance of the rows under it. The full list is in the
#: header comment, which is honest and schema-safe, and the real fix is a field in
#: the consumer's schema rather than a lie in this one.
_PROVENANCE_NOTE = (
    "# `run_id` below is the newest run quoted, not the only one. Rows may come\n"
    "# from any of these, and each row's own run is in that run's directory:\n")

_MAPPING_PROVENANCE = (
    "# Generated by `stem consolidate`. Do not edit, and do not commit a hand edit:\n"
    "# delete this file and run it again, which produces an identical one.\n"
    "#\n"
    "# ONE run, entire, rather than the newest row per obligation. The rows interlock:\n"
    "# `probed-clean` here and `not-probed` there are two statements about the same\n"
    "# selection, so stitching them from two runs would describe a page no run ever\n"
    "# measured. Earlier runs are not merged; they are in the notes. From:\n")

_HEADER = (
    "# Generated by `stem consolidate`. Do not edit, and do not commit a hand edit:\n"
    "# delete this file and run it again, which produces an identical one.\n"
    "#\n"
    "# One row per case, taken from the newest quotable run that measured it. Runs\n"
    "# marked not quotable stay under runs/ and never reach here, which is what\n"
    "# makes running the same case five times while tuning it safe.\n")


def _pins(engagement_dir: str | Path) -> dict[str, str]:
    """Case id -> run id, from `findings.yaml`'s optional `run:`.

    Pinning is how one particular transcript gets quoted when the newest run is
    not the one the write-up describes. Read, never written: `findings.yaml` is a
    human file and nothing here touches it.
    """
    import yaml

    f = Path(engagement_dir) / "findings.yaml"
    if not f.is_file():
        return {}
    try:
        doc = yaml.safe_load(f.read_text(encoding="utf-8"))
    except Exception:  # noqa: BLE001 - a malformed human file is the human's
        return {}
    out: dict[str, str] = {}
    for entry in doc if isinstance(doc, list) else []:
        if not isinstance(entry, dict):
            continue
        case, run = entry.get("case"), entry.get("run")
        if case and run:
            out[str(case)] = str(run)
    return out


def collect(engagement_dir: str | Path) -> tuple[dict, list[str]]:
    """(consolidated measurements, notes) for one engagement.

    `notes` is what a reader needs and a file cannot carry: which runs were
    skipped and why. Returned rather than printed so a caller decides where it
    goes.
    """
    eng = Path(engagement_dir)
    pins = _pins(eng)
    chosen: dict[str, tuple[str, dict]] = {}
    heads: dict[str, dict] = {}
    latest_head: dict = {}
    notes: list[str] = []

    for run in exported_runs(eng):
        if run.name in NEVER_READ:
            continue
        manifest, doc = load_exported_run(run)
        if not doc:
            notes.append(f"{run.name}: no {MEASUREMENTS}, skipped")
            continue
        if manifest.get("quotable") is not True:
            why = manifest.get("not_quotable_because") or "not marked quotable"
            notes.append(f"{run.name}: not quotable ({why}), skipped")
            continue
        # Kept per run rather than overwritten, because the header has to come
        # from a run that actually CONTRIBUTED a row. It used to be reassigned for
        # every quotable run, so when findings.yaml pinned every case to an older
        # run the output's `run_id` named that older run while its config_hash,
        # corpus and target metadata came from the newest one -- a header
        # describing a run none of the rows were measured by. Caught in review.
        heads[str(doc.get("run_id") or run.name)] = {
            k: v for k, v in doc.items() if k != "cases"}
        latest_head = heads[str(doc.get("run_id") or run.name)]
        for row in doc.get("cases") or []:
            cid = str(row.get("case_id") or "")
            if not cid:
                continue
            state = str(row.get("state") or "").lower()
            if state and state not in QUOTABLE_STATES:
                continue
            pinned = pins.get(cid)
            if pinned and pinned != doc.get("run_id"):
                continue
            # Runs arrive oldest first, so a later one simply wins unless a pin
            # named an earlier one.
            chosen[cid] = (str(doc.get("run_id") or run.name), row)

    quoted = sorted({rid for rid, _row in chosen.values()})
    # The newest run that contributed a row, falling back to the newest eligible
    # one only when nothing was selected at all.
    out: dict = dict(heads.get(quoted[-1], latest_head) if quoted else latest_head)
    out["cases"] = [row for _rid, row in
                    (chosen[c] for c in sorted(chosen))]
    if quoted:
        # `run_id` is the newest run quoted, which is the best available answer to
        # a field the consumer's schema types as one string. It is not the whole
        # truth -- see `_PROVENANCE_NOTE` -- and the full list goes in the header
        # comment, which is traceable and schema-safe.
        out["run_id"] = quoted[-1]
    for cid, rid in sorted(pins.items()):
        if cid not in chosen:
            notes.append(f"{cid}: findings.yaml pins run {rid}, which has no "
                         f"quotable measurement for it")
    return out, notes


def collect_mapping(engagement_dir: str | Path) -> tuple[dict, list[str]]:
    """(consolidated control mapping, notes) for one engagement.

    Chosen differently from the measurements, and the difference is the point. A
    measurement is per CASE, so the consolidated file takes the newest quotable run
    for each one. A control mapping is per OBLIGATION over a whole scope, and the
    rows interlock: `probed-clean` on one obligation and `not-probed` on another are
    statements about the same selection, and stitching obligations from two runs
    would produce a page no single run ever measured.

    So the newest quotable run wins entire. Earlier runs are listed in the notes
    rather than merged, because "we also ran this three weeks ago" is a fact about
    the engagement and not a row in this table.
    """
    eng = Path(engagement_dir)
    notes: list[str] = []
    chosen: tuple[str, dict] | None = None
    for run in exported_runs(eng):
        if run.name in NEVER_READ:
            continue
        manifest, _doc = load_exported_run(run)
        path = run / CONTROL_MAPPING
        if not path.is_file():
            continue
        if manifest.get("quotable") is not True:
            why = manifest.get("not_quotable_because") or "not marked quotable"
            notes.append(f"{run.name}: not quotable ({why}), mapping skipped")
            continue
        import yaml

        doc = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        if not doc.get("obligations"):
            notes.append(f"{run.name}: {CONTROL_MAPPING} holds no obligations, skipped")
            continue
        if chosen is not None:
            notes.append(f"{chosen[0]}: superseded as the control mapping by "
                         f"{run.name}, which is newer")
        chosen = (run.name, doc)
    if chosen is None:
        return {}, notes
    return chosen[1], notes


def quoted_runs(doc: dict, engagement_dir: str | Path) -> list[str]:
    """Which runs this consolidated document draws from, newest last."""
    seen: list[str] = []
    for run in exported_runs(Path(engagement_dir)):
        manifest, _doc = load_exported_run(run)
        if manifest.get("quotable") is True:
            seen.append(str(manifest.get("run_id") or run.name))
    return seen


def write(engagement_dir: str | Path) -> tuple[Path, list[str]]:
    """Write the engagement-root measurements file. Returns (path, notes)."""
    import yaml

    eng = Path(engagement_dir)
    if not eng.is_dir():
        raise FileNotFoundError(f"not an engagement directory: {eng}")
    doc, notes = collect(eng)
    out = eng / MEASUREMENTS
    runs = quoted_runs(doc, eng)
    provenance = "".join(f"#   {r}\n" for r in runs) or "#   (none)\n"
    out.write_text(_HEADER + _PROVENANCE_NOTE + provenance + "#\n"
                   + yaml.safe_dump(doc, sort_keys=False, width=100,
                                    allow_unicode=True),
                   encoding="utf-8")
    # The second machine file. Written whenever a run exported one, and absent
    # without complaint when none did: an engagement that has not been scoped
    # against an obligation catalogue has no control mapping to consolidate, which
    # is a fact about the engagement rather than a failure here.
    mapping, mapping_notes = collect_mapping(eng)
    notes.extend(mapping_notes)
    root_mapping = eng / CONTROL_MAPPING
    if not mapping and root_mapping.is_file():
        # A revoked result must not stay in the deliverable. Marking the only
        # source run not quotable used to leave its previously consolidated
        # obligations published at the engagement root, because this only ever
        # WROTE and never removed. Caught in review. Removed rather than left, and
        # said in the notes, because a file silently vanishing is its own surprise.
        root_mapping.unlink()
        notes.append(f"{CONTROL_MAPPING} removed from the engagement root: no "
                     f"quotable run carries one any more, and a consolidated file "
                     f"no run stands behind is a published claim nobody measured")
    if mapping:
        root_mapping.write_text(
            _MAPPING_PROVENANCE
            + f"#   {mapping.get('run_id') or 'unknown run'}\n#\n"
            + yaml.safe_dump(mapping, sort_keys=False, width=100,
                             allow_unicode=True),
            encoding="utf-8")
    return out, notes
