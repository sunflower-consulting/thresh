"""The seam into the deliverable: a run's numbers, as the document generator reads.

This is the only reason a report's figures match the run that produced them. A
number retyped from a terminal into a document is a number nobody can trace, and
the first time it disagrees with the run there is no way to tell which is wrong.

ONE DIRECTORY PER RUN, AND WHY THAT IS NOT THE OBVIOUS SHAPE.

The engine this replaces wrote `<engagement>/measurements.yaml` -- one path per
engagement. It refused to clobber, which was right, and a test pinned the refusal.
But one destination means retests, tuning runs and breadth output all collide
there, and the only way past the refusal is a flag that then destroys the earlier
file. A guard that can only be satisfied by deleting the thing it guards is a
guard that gets passed `--force` every time.

So export writes `<engagement>/runs/<run-id>/` and never touches the engagement
root. Nothing collides, nothing needs forcing, and the five times you ran the same
case while getting it right stay on disk and stay diffable. `consolidate` is what
produces the single file a document reads, from the runs marked quotable.

WHAT THIS REFUSES TO EMIT.

Severity. The document generator wants likelihood and impact as 1-5 integers and a
human sets them, because severity is a judgement about a deployment this
instrument knows nothing about. Deriving it here would put an invented number in a
risk matrix, and it would be the least defensible line in the output.

A row for a finding with no trials. That would render as a measured zero, which is
a different and wronger claim than its absence.
"""
from __future__ import annotations

from pathlib import Path

#: The document generator's schema is `additionalProperties: false`, so this is a
#: contract and not a suggestion: a field not in this tuple is a validation
#: failure in the consuming repo. Ordered, because the row is rebuilt in this
#: order on the way out and a diff between two runs should line up.
CASE_FIELDS = ("case_id", "taxon", "owasp", "state", "strongest_rung",
               "attempts", "hits", "asr", "asr_ci", "control_attempts",
               "control_hits", "control_kind", "p_value", "truncated")

MEASUREMENTS = "measurements.yaml"
CONTROL_MAPPING = "control-mapping.yaml"
MANIFEST = "manifest.yaml"

_HEADER = (
    "# Generated by `thresh export`. Do not edit.\n"
    "#\n"
    "# Every rate here carries the attempt budget it was drawn from and the control\n"
    "# arm it was measured against, because a rate without those is not a\n"
    "# measurement. `config_hash` says which other runs this is comparable with:\n"
    "# change the judge, the ladder or the models and it moves.\n")


_MAPPING_HEADER = (
    "# Generated by `thresh export`. Do not edit.\n"
    "#\n"
    "# One row per obligation the engagement was scoped to, INCLUDING the ones\n"
    "# nothing was established about. `probed-clean` means a technique bearing on it\n"
    "# ran and nothing stood up, which is a result; `not-probed` means nothing\n"
    "# bearing on it ran, which is not. The `taxa` section says how the obligation\n"
    "# dataset stands on each technique the run touched, because one it has never\n"
    "# seen contributes to no row above and would otherwise leave no trace.\n")


def _case_id(finding: dict) -> str:
    """The corpus id when the case came from the corpus, else the built-in's id.

    The corpus id is what a report cites and what a reader greps for. A run id
    would be technically correct and unusable.
    """
    if finding.get("corpus_id"):
        return str(finding["corpus_id"])
    cases = finding.get("test_cases") or []
    return str(cases[0]) if cases else str(finding.get("id") or "")


def _rung_name(value) -> str:
    """The rung NAME, from any of the three shapes this field arrives in.

    `EvidenceStrength` mixes in int, and the value reaches here differently
    depending on the path the finding took:

        a live member      EvidenceStrength.CANARY
        a run bundle       "CANARY"            (dumped by name)
        a json model_dump  5                   (dumped by value)

    `str()` was applied to all three. On the first it yields
    "EvidenceStrength.CANARY", a python repr in a document a client reads; on the
    third it yields "5". Both validated, because the renderer declared the field
    a bare string. It now carries an enum of the six names and refuses either.

    NONE is 0 and therefore falsy, so a truthiness test skipped it and the row
    omitted the field entirely for every case where nothing fired. A reader then
    could not tell "nothing fired" from "this was never populated", which is the
    one distinction this package exists to keep. It is emitted explicitly.
    """
    from sunflower_thresh.schemas.finding import EvidenceStrength

    name = getattr(value, "name", None)
    if name:
        return str(name)
    if isinstance(value, bool):          # before int: bool is an int subclass
        return str(value)
    if isinstance(value, int):
        try:
            return EvidenceStrength(value).name
        except ValueError:
            return str(value)
    return str(value)


def _row(finding: dict) -> dict | None:
    """One case's measurement, or None when there is nothing measured to report.

    None rather than a row of zeroes. A finding with no `trials` was not measured
    by an attempt budget at all, and emitting `attempts: 0` would render as a
    measured zero -- a different and wronger claim than its absence.
    """
    trials = finding.get("trials")
    if not isinstance(trials, dict) or not trials:
        return None
    row: dict = {"case_id": _case_id(finding)}
    for src, dst in (("taxon", "taxon"), ("owasp", "owasp"), ("state", "state")):
        if finding.get(src):
            row[dst] = str(finding[src])
    if finding.get("evidence_strength") is not None:
        row["strongest_rung"] = _rung_name(finding["evidence_strength"])
    row["attempts"] = int(trials.get("trials") or 0)
    row["hits"] = int(trials.get("hits") or 0)
    if trials.get("asr") is not None:
        row["asr"] = float(trials["asr"])
    ci = trials.get("asr_ci")
    if isinstance(ci, (list, tuple)) and len(ci) == 2:
        row["asr_ci"] = [float(ci[0]), float(ci[1])]
    row["control_attempts"] = int(trials.get("control_trials") or 0)
    row["control_hits"] = int(trials.get("control_hits") or 0)
    row["control_kind"] = str(trials.get("control_kind") or "")
    if trials.get("p_value") is not None:
        row["p_value"] = float(trials["p_value"])
    # Always emitted, even when false. "The budget ran out" and "nobody said" are
    # different claims and a reader cannot tell them apart from an absent key.
    row["truncated"] = bool(trials.get("truncated", False))
    return {k: row[k] for k in CASE_FIELDS if k in row}


def measurements(manifest: dict, findings: list[dict]) -> dict:
    """The document a report's measurement appendix renders from. Pure: no IO."""
    doc: dict = {"run_id": str(manifest.get("run_id") or ""),
                 "generated_by": f"thresh {manifest.get('stem_version') or ''}".strip()}
    for key in ("config_hash", "corpus_sha", "plan_hash", "roe_hash",
                "target_family", "target_config"):
        if manifest.get(key):
            doc[key] = str(manifest[key])
    rows = [r for r in (_row(f) for f in findings) if r is not None]
    doc["cases"] = sorted(rows, key=lambda r: r["case_id"])
    return doc


def run_dir_for(engagement_dir: str | Path, run_id: str) -> Path:
    return Path(engagement_dir) / "runs" / run_id


def write_run(engagement_dir: str | Path, manifest: dict,
              findings: list[dict],
              control_mapping: dict | None = None) -> Path:
    """Write one run's export under `<engagement>/runs/<run-id>/`.

    No `force` parameter, and its absence is the design. A run id is unique, so
    there is nothing to collide with and nothing to overwrite; if the directory
    exists this run has already been exported and writing it again is idempotent
    rather than destructive.

    `control_mapping` is `obligations.coverage()`'s document, passed in rather than
    computed here. This module writes files; deciding which regulatory obligation a
    technique produces evidence about is a judgement that belongs where the
    judgement is recorded, and keeping it out of here also keeps the vendored
    200KB dataset off the import path of an export that does not need it.

    It arrives with the run's own `run_id` forced in, because the consuming schema
    requires that field at the top level and the engine this was ported from never
    emitted it -- so every control mapping it wrote would have failed validation on
    a required key.
    """
    import yaml

    eng = Path(engagement_dir)
    if not eng.is_dir():
        raise FileNotFoundError(f"not an engagement directory: {eng}")
    rid = str(manifest.get("run_id") or "").strip()
    if not rid:
        raise ValueError("the run manifest carries no run_id, so there is "
                         "nowhere to write it")
    out = run_dir_for(eng, rid)
    out.mkdir(parents=True, exist_ok=True)
    (out / MANIFEST).write_text(
        "# Copied from the run bundle by `thresh export`. Do not edit.\n"
        + yaml.safe_dump(manifest, sort_keys=False, width=100,
                         allow_unicode=True),
        encoding="utf-8")
    (out / MEASUREMENTS).write_text(
        _HEADER + yaml.safe_dump(measurements(manifest, findings),
                                 sort_keys=False, width=100, allow_unicode=True),
        encoding="utf-8")
    mapping_path = out / CONTROL_MAPPING
    if control_mapping is not None:
        doc = {**control_mapping, "run_id": rid}
        mapping_path.write_text(
            _MAPPING_HEADER + yaml.safe_dump(doc, sort_keys=False, width=100,
                                             allow_unicode=True),
            encoding="utf-8")
    elif mapping_path.is_file():
        # This export has no mapping, so the run must not keep the one a previous
        # export left. Removing the engagement's regulatory scope, or passing
        # --no-control-mapping, used to leave the old file in place for
        # `consolidate` to pick up while the CLI reported that none was written.
        # Caught in review. The file is generated, so removing it is safe; nothing
        # here touches a file a human wrote.
        mapping_path.unlink()
    return out


def load_exported_run(run_dir: str | Path) -> tuple[dict, dict, list[str]]:
    """(manifest, measurements, faults) for one exported run.

    Missing is empty and not fatal, because one unreadable run is not the set. But
    absent and UNREADABLE both yielded an empty dict and the caller could not tell
    them apart, so a corrupt `manifest.yaml` reached a reader as "not quotable (not
    marked quotable), skipped" -- a decision somebody made, reported for a run that
    may well have been marked quotable and whose rows are now missing from the
    deliverable. A fault and a policy must not render alike.

    `faults` names each file that EXISTS and could not be read. Empty is the
    ordinary case, so a caller that ignores it behaves exactly as before.
    """
    import yaml

    d = Path(run_dir)
    out: list[dict] = []
    faults: list[str] = []
    for name in (MANIFEST, MEASUREMENTS):
        f = d / name
        if not f.is_file():
            out.append({})
            continue
        try:
            out.append(yaml.safe_load(f.read_text(encoding="utf-8")) or {})
        except Exception as exc:  # noqa: BLE001 - one unreadable run is not the set
            faults.append(f"{name} exists and could not be read: {exc}")
            out.append({})
    return out[0], out[1], faults


def exported_runs(engagement_dir: str | Path) -> list[Path]:
    """Every exported run directory, oldest first.

    Sorted by name, which sorts chronologically because a run id leads with its
    timestamp. That ordering is what "the newest quotable run" means below.
    """
    runs = Path(engagement_dir) / "runs"
    if not runs.is_dir():
        return []
    return sorted((d for d in runs.iterdir() if d.is_dir()), key=lambda d: d.name)
